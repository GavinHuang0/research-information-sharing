"""Execute separate development/freeze, final, and reporting stages of the fixed pilot.

No final forecasts are generated by --stage development. Final execution requires
an unchanged frozen manifest created from primary development scores.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import gzip
import hashlib
from importlib.metadata import version
import json
import os
from pathlib import Path
import platform
import subprocess
import sys
import tomllib

# Set before importing NumPy/sklearn; small repeated fits otherwise oversubscribe.
for variable in ("OPENBLAS_NUM_THREADS", "OMP_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ[variable] = "1"
os.environ.setdefault("MPLCONFIGDIR", str(Path(__file__).resolve().parents[1] / ".venv/matplotlib-cache"))
Path(os.environ["MPLCONFIGDIR"]).mkdir(parents=True, exist_ok=True)

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from factorcast.data import load_daily_returns
from factorcast.pilot import S, policies, prepare_panels, run_stage
from factorcast.pilot_reporting import choose_winners, summarize, write_reports


def sha(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def json_write(path: Path, value) -> None:
    path.write_bytes((json.dumps(value, indent=2, sort_keys=True, default=str) + "\n").encode())


def code_manifest() -> dict:
    paths = sorted((ROOT / "src/factorcast").glob("*.py")) + [Path(__file__).resolve()]
    paths += [ROOT / "requirements-lock.txt", ROOT / "requirements-analysis-lock.txt", ROOT / "docs/fixed_pilot_protocol.md"]
    return {path.relative_to(ROOT).as_posix(): sha(path.read_bytes().replace(b"\r\n", b"\n")) for path in paths}


def csv_write(path: Path, frame: pd.DataFrame) -> None:
    with gzip.GzipFile(filename=str(path), mode="wb", mtime=0) as stream:
        stream.write(frame.to_csv(index=False, float_format="%.17g", lineterminator="\n").encode())


def progress(record: dict) -> None:
    print(json.dumps(dict(event="refit_complete", **record), default=str), flush=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=ROOT / "configs/fixed_pilot.toml")
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--stage", required=True, choices=("development", "final", "report"))
    args = parser.parse_args()
    config_bytes = args.config.read_bytes()
    config = tomllib.loads(config_bytes.decode())
    if tuple(config["design"]["targets"]) != S or tuple(config["design"]["small_panel"]) != S:
        parser.error("This pilot requires the fixed six targets and common panel S")
    if config["experiment"]["factor_count"] != 2:
        parser.error("This pilot fixes two components")
    output = args.output.resolve()
    frozen_path = output / "frozen_procedure.json"
    fingerprint = dict(config_sha256=sha(config_bytes), code_sha256_lf=code_manifest(),
                       versions={name: version(name) for name in ("numpy", "pandas", "scipy", "scikit-learn", "matplotlib")})
    if args.stage != "development":
        frozen = json.loads(frozen_path.read_bytes())
        if frozen["fingerprint"] != fingerprint:
            parser.error("Code, protocol, dependencies, or configuration changed after freezing")
        dev_path = output / "development/predictions.csv.gz"
        if sha(dev_path.read_bytes()) != frozen["development_predictions_sha256"]:
            parser.error("Development predictions changed after freezing")
        for name, expected in frozen["development_files_sha256"].items():
            if sha((output / "development" / name).read_bytes()) != expected:
                parser.error(f"Development artifact changed after freezing: {name}")
        if args.stage == "report":
            final_manifest = json.loads((output / "final/stage_manifest.json").read_bytes())
            for name, expected in final_manifest["files"].items():
                if sha((output / "final" / name).read_bytes()) != expected:
                    parser.error(f"Final artifact changed after scoring: {name}")
            frames = [pd.read_csv(output / stage / "predictions.csv.gz") for stage in ("development", "final")]
            write_reports(pd.concat(frames, ignore_index=True), output / "reports", frozen["winners"])
            print(f"Reports saved to {output / 'reports'}", flush=True)
            return
    elif output.exists():
        parser.error("Output already exists; use a new run directory")

    provenance_path = ROOT / config["data"]["provenance"]
    source = json.loads(provenance_path.read_bytes())
    returns = {}
    inputs = {}
    for weighting in ("value", "equal"):
        path = ROOT / config["data"][f"{weighting}_returns"]
        raw = path.read_bytes()
        if sha(raw) != source["panels"][weighting]["sha256"]:
            parser.error(f"Archived input checksum mismatch: {weighting}")
        inputs[weighting] = dict(path=path.relative_to(ROOT).as_posix(), sha256=sha(raw), bytes=len(raw))
        returns[weighting] = load_daily_returns(path, units=config["data"]["units"])
    inputs["provenance"] = dict(path=provenance_path.relative_to(ROOT).as_posix(), sha256=sha(provenance_path.read_bytes()))
    datasets, calendar = prepare_panels(returns, config)
    if args.stage == "final" and inputs != frozen["inputs"]:
        parser.error("Input files changed after freezing")
    if args.stage == "development":
        output.mkdir(parents=True, exist_ok=False)
        (output / "config.toml").write_bytes(config_bytes)
        (output / "protocol.md").write_bytes((ROOT / "docs/fixed_pilot_protocol.md").read_bytes())
        json_write(output / "calendar.json", calendar)
        json_write(output / "policies.json", policies(config))
        git = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True)
        status = subprocess.run(["git", "status", "--porcelain"], cwd=ROOT, capture_output=True, text=True)
        json_write(output / "metadata.json", dict(started_at_utc=datetime.now(timezone.utc).isoformat(),
                   fingerprint=fingerprint, inputs=inputs, python=sys.version, platform=platform.platform(),
                   git_commit=git.stdout.strip(), git_dirty=bool(status.stdout.strip()),
                   aggregation=config["selection"]["aggregation"],
                   outcome_loss="mean held-out per-week target squared log-variance error; no fitted errors, donor errors, or penalties"))
    stage_dir = output / args.stage
    stage_dir.mkdir(exist_ok=False)
    print(json.dumps(dict(event="stage_started", stage=args.stage, time_utc=datetime.now(timezone.utc).isoformat())), flush=True)
    predictions, tuning, timing = run_stage(datasets, config, args.stage, progress=progress)
    csv_write(stage_dir / "predictions.csv.gz", predictions)
    with gzip.GzipFile(filename=str(stage_dir / "tuning.jsonl.gz"), mode="wb", mtime=0) as stream:
        for row in tuning:
            stream.write((json.dumps(row, sort_keys=True, default=str) + "\n").encode())
    per_target, aggregate = summarize(predictions)
    if set(aggregate.n_targets) != {6} or len(aggregate) != 36:
        raise AssertionError("Every phase must report all 18 policies, six targets, and two weightings")
    per_target.to_csv(stage_dir / "target_summary.csv", index=False, lineterminator="\n")
    aggregate.to_csv(stage_dir / "aggregate_summary.csv", index=False, lineterminator="\n")
    json_write(stage_dir / "timing.json", timing)
    stage_hashes = {path.name: sha(path.read_bytes()) for path in stage_dir.iterdir() if path.is_file()}
    json_write(stage_dir / "stage_manifest.json", dict(completed_at_utc=datetime.now(timezone.utc).isoformat(), files=stage_hashes))
    if args.stage == "development":
        winners = choose_winners(aggregate)
        json_write(frozen_path, dict(frozen_at_utc=datetime.now(timezone.utc).isoformat(),
                   fingerprint=fingerprint, inputs=inputs, winners=winners,
                   development_predictions_sha256=sha((stage_dir / "predictions.csv.gz").read_bytes()),
                   development_files_sha256=stage_hashes,
                   primary_development_scores=aggregate[aggregate.weighting == "value"].sort_values(["mean_ratio_mse", "policy_id"]).to_dict(orient="records"),
                   selection_rule=config["selection"], final_scores_computed=False,
                   final_stage_policy="All prespecified comparators evaluated; winner identity cannot change. Historical-only scheduled tuning continues."))
        print(json.dumps(dict(event="procedure_frozen", winners=winners)), flush=True)
    print(json.dumps(dict(event="stage_complete", stage=args.stage, timing=timing)), flush=True)


if __name__ == "__main__":
    main()
